package org.jwcarman.roux.roles.check;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.SequencedMap;
import java.util.stream.Collectors;
import java.util.stream.Stream;

import org.jwcarman.roux.roles.Permissions;

/**
 * The frontend's list of permissions, generated from the server's constants, so it is never written
 * by hand and never drifts: each constant under its Java name, and {@code PERMISSIONS}, the array
 * the navigation takes. The app's roles test calls {@link #verify}, which rewrites the committed
 * file and fails when it is stale.
 */
public final class PermissionsTypeScript {

  private PermissionsTypeScript() {}

  /**
   * Renders the file.
   *
   * @param types the classes declaring permissions, as {@link Permissions#allOf} takes them
   * @return the TypeScript source
   * @throws IllegalArgumentException when two classes give one field name different values, which
   *     would not compile, or as {@link Permissions#constantsOf} throws
   */
  public static String render(Class<?>... types) {
    SequencedMap<Class<?>, SequencedMap<String, String>> constants = Permissions.constantsOf(types);
    Map<String, String> byName = new LinkedHashMap<>();
    Map<String, Class<?>> declaredBy = new LinkedHashMap<>();
    constants.forEach(
        (type, named) ->
            named.forEach(
                (name, value) -> {
                  String earlier = byName.putIfAbsent(name, value);
                  if (earlier == null) {
                    declaredBy.put(name, type);
                  } else if (!earlier.equals(value)) {
                    throw new IllegalArgumentException(
                        name
                            + " is declared by both "
                            + declaredBy.get(name).getName()
                            + " and "
                            + type.getName()
                            + " with different values; rename one");
                  }
                }));
    String header =
        constants.sequencedKeySet().stream()
            .map(Class::getSimpleName)
            .collect(Collectors.joining(", "));
    String declarations =
        byName.entrySet().stream()
            .map(entry -> "export const " + entry.getKey() + " = \"" + entry.getValue() + "\";")
            .collect(Collectors.joining("\n"));
    return Stream.of(
            "// Generated by roux from "
                + header
                + ": do not edit. The app's permissions test rewrites it when it is stale.\n",
            declarations + "\n",
            "/** Every permission there is: what the navigation's items may need. */\n"
                + "export const PERMISSIONS = ["
                + String.join(", ", byName.keySet())
                + "] as const;\n",
            "export type Permission = (typeof PERMISSIONS)[number];\n")
        .collect(Collectors.joining("\n"));
  }

  /**
   * Checks the committed file is current, rewriting it when it is not.
   *
   * @param file the committed file, such as {@code frontend/src/permissions.gen.ts}
   * @param types the classes declaring permissions
   * @throws AssertionError when the file was missing or stale; it has been rewritten, to commit
   */
  public static void verify(Path file, Class<?>... types) {
    String rendered = render(types);
    try {
      if (Files.exists(file) && Files.readString(file).equals(rendered)) {
        return;
      }
      Files.writeString(file, rendered);
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
    throw new AssertionError(file + " was stale and has been rewritten: commit it");
  }
}
