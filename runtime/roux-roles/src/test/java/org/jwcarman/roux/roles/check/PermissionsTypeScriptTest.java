package org.jwcarman.roux.roles.check;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatIllegalArgumentException;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;

import org.junit.jupiter.api.DisplayNameGeneration;
import org.junit.jupiter.api.DisplayNameGenerator.ReplaceUnderscores;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

@DisplayNameGeneration(ReplaceUnderscores.class)
class PermissionsTypeScriptTest {

  public static final class A {
    public static final String X = "a.x";
    public static final String Y = "a.y";
  }

  public static final class B {
    public static final String Y = "a.y";
    public static final String Z = "b.z";
  }

  public static final class C {
    public static final String Y = "c.y";
  }

  private static final String EXPECTED =
      """
      // Generated by roux from A, B: do not edit. The app's permissions test rewrites it when it is stale.

      export const X = "a.x";
      export const Y = "a.y";
      export const Z = "b.z";

      /** Every permission there is: what the navigation's items may need. */
      export const PERMISSIONS = [X, Y, Z] as const;

      export type Permission = (typeof PERMISSIONS)[number];
      """;

  @TempDir Path dir;

  @Test
  void renders_each_constant_once_and_the_list() {
    assertThat(PermissionsTypeScript.render(A.class, B.class)).isEqualTo(EXPECTED);
  }

  @Test
  void one_name_with_two_values_fails_naming_both_classes() {
    assertThatIllegalArgumentException()
        .isThrownBy(() -> PermissionsTypeScript.render(A.class, C.class))
        .withMessageContaining("Y")
        .withMessageContaining(A.class.getName())
        .withMessageContaining(C.class.getName());
  }

  @Test
  void a_missing_file_is_written_and_fails() {
    Path file = dir.resolve("permissions.gen.ts");

    assertThatThrownBy(() -> PermissionsTypeScript.verify(file, A.class, B.class))
        .isInstanceOf(AssertionError.class)
        .hasMessageContaining("was stale");
    assertThat(file).hasContent(EXPECTED);
  }

  @Test
  void a_stale_file_is_rewritten_and_fails() throws Exception {
    Path file = Files.writeString(dir.resolve("permissions.gen.ts"), "old");

    assertThatThrownBy(() -> PermissionsTypeScript.verify(file, A.class, B.class))
        .isInstanceOf(AssertionError.class)
        .hasMessage(file + " was stale and has been rewritten: commit it");
    assertThat(Files.readString(file)).isEqualTo(EXPECTED);
  }

  @Test
  void a_current_file_is_left_alone() throws Exception {
    Path file = Files.writeString(dir.resolve("permissions.gen.ts"), EXPECTED);
    FileTime before = FileTime.fromMillis(1_000_000L);
    Files.setLastModifiedTime(file, before);

    PermissionsTypeScript.verify(file, A.class, B.class);

    assertThat(Files.getLastModifiedTime(file)).isEqualTo(before);
  }

  @Test
  void a_file_that_cannot_be_read_fails() throws Exception {
    Path directory = Files.createDirectory(dir.resolve("permissions.gen.ts"));

    assertThatThrownBy(() -> PermissionsTypeScript.verify(directory, A.class))
        .isInstanceOf(UncheckedIOException.class);
  }
}
