package org.jwcarman.roux.problems;

import static org.springframework.security.test.web.servlet.request.SecurityMockMvcRequestPostProcessors.user;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.context.annotation.Import;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.MockMvc;

/**
 * The test classpath carries an application-level {@code ValidationMessages.properties} with an
 * unrelated key, as an app with a custom constraint would. roux's messages must still show.
 */
@SpringBootTest(classes = ProblemsTestApplication.class)
@AutoConfigureMockMvc
@Import(ProblemsTestController.class)
class ContributedValidationMessagesTest {

  @Autowired MockMvc mvc;

  @Test
  void anApplicationBundleDoesNotHideTheContributedMessages() throws Exception {
    mvc.perform(
            post("/api/test/problems/named")
                .with(user("tester"))
                .contentType(MediaType.APPLICATION_JSON)
                .content("{\"name\":\"\"}"))
        .andExpect(status().isBadRequest())
        .andExpect(jsonPath("$.errors[0].message").value("Must not be blank"));
  }
}
