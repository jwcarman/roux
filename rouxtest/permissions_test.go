package rouxtest_test

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"testing"

	"github.com/jwcarman/roux/rouxtest"
)

const wantTS = `// Generated by roux from the application's permissions: do not edit. Its permissions test
// (cmd/server) rewrites it when they change.

export const ADMIN = "roux.admin";
export const ITEMS_READ = "items.read";
export const ITEMS_DELETE_ANY = "items.delete.any";

/** Every permission there is: what the navigation's items may need. */
export const PERMISSIONS = [ADMIN, ITEMS_READ, ITEMS_DELETE_ANY] as const;

export type Permission = (typeof PERMISSIONS)[number];
`

func TestAStalePermissionsFileIsRewrittenAndFails(t *testing.T) {
	path := filepath.Join(t.TempDir(), "permissions.gen.ts")
	if err := os.WriteFile(path, []byte("stale"), 0o600); err != nil {
		t.Fatal(err)
	}
	inner := &recorder{}
	ran := runIn(inner, func(tt rouxtest.T) {
		rouxtest.PermissionsFile(tt, path, "roux.admin", "items.read", "items.delete.any")
	})
	if !ran || !inner.Failed() {
		t.Fatal("a stale file passed")
	}
	got, err := os.ReadFile(path)
	if err != nil || string(got) != wantTS {
		t.Fatalf("rewritten as:\n%s\nwant:\n%s", got, wantTS)
	}
	// Now it is current: it passes and is left alone.
	rouxtest.PermissionsFile(t, path, "roux.admin", "items.read", "items.delete.any")
}

func TestAPermissionListedTwiceIsAMistake(t *testing.T) {
	inner := &recorder{}
	runIn(inner, func(tt rouxtest.T) {
		rouxtest.PermissionsFile(tt, filepath.Join(t.TempDir(), "p.ts"), "items.read", "items.read")
	})
	if !inner.Failed() {
		t.Fatal("a duplicate passed")
	}
}

// recorder is a rouxtest.T that notes a failure; Fatalf ends its goroutine, as a test's does.
type recorder struct {
	failed bool
	msgs   []string
}

func (*recorder) Helper() {}
func (r *recorder) Errorf(format string, args ...any) {
	r.failed = true
	r.msgs = append(r.msgs, fmt.Sprintf(format, args...))
}
func (r *recorder) Fatalf(format string, args ...any) {
	r.Errorf(format, args...)
	runtime.Goexit()
}
func (r *recorder) Failed() bool { return r.failed }

// runIn runs fn with tt in a goroutine of its own, as a test does, so a Fatalf ends only it.
func runIn(tt rouxtest.T, fn func(rouxtest.T)) bool {
	done := make(chan bool)
	go func() {
		defer func() { done <- true }()
		fn(tt)
	}()
	return <-done
}

func TestTheGrantsMatchThePermissionsThereAre(t *testing.T) {
	a := rouxtest.New(t, "rouxtest_grants")
	var roux []string
	rows, err := a.Pool.Query(t.Context(), `select distinct permission from roux_role_permission order by 1`)
	if err != nil {
		t.Fatal(err)
	}
	for rows.Next() {
		var p string
		if err := rows.Scan(&p); err != nil {
			t.Fatal(err)
		}
		roux = append(roux, p)
	}
	a.Role("OWNER", "notes.read")
	a.Role("PLAYER", "notes.read")
	rouxtest.CheckGrants(t, a.Pool, append(roux, "notes.read")...)

	for name, declared := range map[string][]string{
		"a grant nobody declares": roux,
		"an owner without one":    append(roux, "notes.read", "notes.write"),
	} {
		r := &recorder{}
		runIn(r, func(tt rouxtest.T) { rouxtest.CheckGrants(tt, a.Pool, declared...) })
		if !r.Failed() {
			t.Errorf("%s passed", name)
		}
	}
}
