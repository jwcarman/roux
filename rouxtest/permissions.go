// T is what the checks need of a test: *testing.T is one.
type T interface {
	Helper()
	Errorf(format string, args ...any)
	Fatalf(format string, args ...any)
}

// PermissionsFile keeps the front end's list of permissions (frontend/src/permissions.gen.ts)
// the same as the server's, so it is never written by hand: each permission a constant named
// after it (items.delete.any is ITEMS_DELETE_ANY; roux's own drop "roux.", so roux.admin is
// ADMIN), and PERMISSIONS, every one, for the navigation. When the file is not what the
// permissions make, it rewrites the file and fails, so the change is seen and committed.
func PermissionsFile(t T, path string, permissions ...string) {
	t.Helper()
	for i, p := range permissions {
		if slices.Contains(permissions[:i], p) {
			t.Fatalf("rouxtest: permission %q is listed twice", p)
		}
	}
	want := permissionsTS(permissions)
	got, err := os.ReadFile(path)
	if err == nil && string(got) == want {
		return
	}
	if err := os.WriteFile(path, []byte(want), 0o600); err != nil {
		t.Fatalf("rouxtest: writing %s: %v", path, err)
	}
	t.Errorf("rouxtest: %s did not list the server's permissions; it is rewritten: commit it", path)
}

// tsName is a permission's constant: upper case, dots as underscores, roux's prefix dropped.
func tsName(permission string) string {
	return strings.ToUpper(strings.ReplaceAll(strings.TrimPrefix(permission, "roux."), ".", "_"))
}

func permissionsTS(permissions []string) string {
	var b strings.Builder
	b.WriteString("// Generated by roux from the application's permissions: do not edit. Its permissions test\n")
	b.WriteString("// (cmd/server) rewrites it when they change.\n\n")
	names := make([]string, len(permissions))
	for i, p := range permissions {
		names[i] = tsName(p)
		fmt.Fprintf(&b, "export const %s = %q;\n", names[i], p)
	}
	b.WriteString("\n/** Every permission there is: what the navigation's items may need. */\n")
	list := strings.Join(names, ", ")
	if len("export const PERMISSIONS = [")+len(list)+len("] as const;") <= 80 {
		fmt.Fprintf(&b, "export const PERMISSIONS = [%s] as const;\n", list)
	} else {
		b.WriteString("export const PERMISSIONS = [\n")
		for _, n := range names {
			fmt.Fprintf(&b, "  %s,\n", n)
		}
		b.WriteString("] as const;\n")
	}
	b.WriteString("\nexport type Permission = (typeof PERMISSIONS)[number];\n")
	return b.String()
}

// CheckGrants is the check an application's roles test runs after all its migrations: OWNER holds
// exactly the permissions there are, and no role grants one nobody declares. A forgotten grant or
// a typo in a migration fails it, naming the permission.
func CheckGrants(t T, db page.Querier, permissions ...string) {
	t.Helper()
	ctx := context.Background()
	rows, err := db.Query(ctx, `
		select r.name, rp.permission
		  from roux_role_permission rp join roux_role r on r.id = rp.role_id
		 order by r.name, rp.permission`)
	if err != nil {
		t.Fatalf("rouxtest: reading the grants: %v", err)
	}
	type grant struct{ Role, Permission string }
	grants, err := pgx.CollectRows(rows, pgx.RowToStructByPos[grant])
	if err != nil {
		t.Fatalf("rouxtest: reading the grants: %v", err)
	}
	owner := map[string]bool{}
	for _, g := range grants {
		if !slices.Contains(permissions, g.Permission) {
			t.Errorf("rouxtest: %s is granted %q, which no permission declares", g.Role, g.Permission)
		}
		if g.Role == authz.RoleOwner {
			owner[g.Permission] = true
		}
	}
	for _, p := range permissions {
		if !owner[p] {
			t.Errorf("rouxtest: %s does not hold %q: grant it in the migration that adds it", authz.RoleOwner, p)
		}
	}
}
